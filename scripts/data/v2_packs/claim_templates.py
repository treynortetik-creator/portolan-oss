def build_prompt(
    vertical_name: str,
    vendor_what: str,
    product_kinds: list[str],
    role_titles: list[str],
    decoy_specs: list[dict],
    exclusion_note: str = "",
) -> tuple[str, str]:
    fact_defs = {
        "usage": "How the product is used, how much, where",
        "complaint": "The customer reports something went wrong",
        "risk": "Evidence the relationship or revenue is threatened",
        "praise": "The customer says something works well",
        "question": "The customer asked something and did not get an answer",
        "decision": "Something was decided",
        "pricing": "Price, discount, budget or invoice discussion",
        "request": "The customer asks for something that does not exist yet",
        "competitor_mention": "A named competitor comes up",
        "contact_change": "A person's role, presence or contact info changed",
        "commitment": "Either side promises something",
        "other": "Durable fact that fits none of the above, still worth recording",
    }

    slot_lines = []
    for fact_type, slots in FACT_TYPE_EVENT_SLOTS.items():
        for event_type, count in slots:
            allowed = sorted(slot_allowed_placeholders(fact_type, event_type))
            slot_lines.append(
                f'- fact_type="{fact_type}" event_type="{event_type}" count={count} '
                f"allowed_placeholders={allowed}"
            )
    slots_block = "\n".join(slot_lines)
    fact_def_block = "\n".join(f"- {ft}: {d}" for ft, d in fact_defs.items())

    decoy_lines = [
        f'- id="{d["id"]}" near_type="{d["near_type"]}" description="{d["description"]}"'
        for d in decoy_specs
    ]
    decoy_block = "\n".join(decoy_lines)

    exclusion_block = (
        f"\nHARD EXCLUSION -- read carefully: {exclusion_note}\n" if exclusion_note else ""
    )

    system = (
        "You write short, plain, business-register template sentences for a B2B "
        "healthcare-software synthetic data generator. You output ONLY valid JSON, "
        "no markdown fences, no commentary before or after the JSON object."
    )

    user = f"""Vertical: {vertical_name}
What this vendor sells: {vendor_what}
Example product archetypes: {", ".join(product_kinds)}
Example customer-side buyer roles: {", ".join(role_titles)}
{exclusion_block}
TASK 1 -- claim templates.

Each "fact type" below is a category of business fact a CRM/call/ticket/email
might record about a customer account. For each (fact_type, event_type, count)
slot listed, write exactly `count` DISTINCT template sentences suitable for
that fact type occurring in that kind of event.

Rules for every template sentence:
1. Plain, declarative, third-person business register (not stylized, not
   casual, not hedged -- that styling is applied later by a different stage).
2. Contains ONLY placeholder tokens from that slot's `allowed_placeholders`
   list, written EXACTLY as literal text, e.g. `{{account}}`, `{{product}}` --
   never fill them in with a real name, never invent a new placeholder token,
   never use a placeholder not in that slot's own allowed list.
3. Every sentence must be grammatically complete and make sense with ANY
   value substituted for each placeholder.
4. Vary sentence structure and scenario angle across the `count` sentences
   for one slot -- different clause order, different framing, different
   business detail -- not just synonym swaps of the same sentence.
5. Keep each sentence under 30 words.
6. Do not repeat a sentence (even reworded) across DIFFERENT slots of the
   same fact_type -- all templates for one fact_type, across every event_type
   slot, must be mutually distinct.
7. No markdown, no numbering, no quotes-within-quotes issues -- plain text
   inside the JSON string.

Fact type meanings:
{fact_def_block}

Slots (fact_type, event_type, how many sentences, allowed placeholders):
{slots_block}

TASK 2 -- decoy examples.

For each decoy class below, write ONE realistic example sentence (in this
vertical's voice) of the near-miss pattern described -- a statement that
LOOKS like a fact but is NOT one (a hypothetical, a negation, hearsay about
another company, generic industry chatter, a rhetorical question, vendor-
internal speculation, an already-resolved issue told as history, or a
commitment/decision confusable pair). Write them as FULLY REALIZED, informal,
first-person-sounding sentences a real person might actually say.

**Critical: invent a specific, concrete, made-up name for anything you'd
otherwise leave blank -- a competitor, a product, a person -- write that
made-up name directly into the sentence as plain text. NEVER write a
curly-brace placeholder like `{{competitor}}` or `{{product}}` in a decoy;
those are only for TASK 1's claim templates, never for decoys.** Two
correctly-shaped decoy examples (note the invented names "Meridian" and
"the old portal", written as plain text, never in braces):
- "We looked at Meridian's platform last spring but stuck with what we
  have since the integration was already dialed in."
- "If the sync job ever failed two nights in a row, that would be a real
  problem for the billing team."

Decoy classes:
{decoy_block}

Respond with ONLY this JSON shape, nothing else:
{{
  "claim_templates": {{
    "<fact_type>": {{
      "<event_type>": ["sentence 1", "sentence 2", ...]
    }}
  }},
  "decoy_examples": {{
    "<decoy_id>": "example sentence"
  }}
}}
"""
    return system, user


def _strip_trailing_commas(s: str) -> str:
    return re.sub(r",(\s*[}\]])", r"\1", s)


_VALID_ESCAPE_CHARS = set('"\\/bfnrtu')


def _fix_bad_escapes(s: str) -> str:
    r"""A model occasionally writes a lone backslash (an em-dash typo, a
    stray "\%" or similar) that is not a valid JSON escape -- double it so
    `json.loads` sees `\\` (a literal backslash) instead of an invalid
    escape sequence."""
    out = []
    i = 0
    while i < len(s):
        ch = s[i]
        if ch == "\\" and i + 1 < len(s) and s[i + 1] not in _VALID_ESCAPE_CHARS:
            out.append("\\\\")
            i += 1
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def extract_json(text: str) -> dict:
    text = text.strip()
    text = re.sub(r"^```(?:json)?\s*", "", text)
    text = re.sub(r"\s*```$", "", text)
    text = text.strip()
    candidates = [text]
    start, end = text.find("{"), text.rfind("}")
    if start != -1 and end != -1 and end > start:
        candidates.append(text[start : end + 1])
    for candidate in list(candidates):
        candidates.append(_strip_trailing_commas(candidate))
    for candidate in list(candidates):
        candidates.append(_fix_bad_escapes(candidate))
    last_err: Exception | None = None
    for candidate in candidates:
        try:
            return json.loads(candidate)
        except json.JSONDecodeError as exc:
            last_err = exc
    raise ValueError(f"could not extract JSON from model output (len={len(text)}): {last_err}")


def build_topup_prompt(
    vertical_name: str,
    vendor_what: str,
    exclusion_note: str,
    fact_type: str,
    event_type: str,
    needed: int,
    existing: list[str],
) -> tuple[str, str]:
    """Asks for `needed` more DISTINCT template sentences for a single
    (fact_type, event_type) slot, given the sentences already kept (so
    the model doesn't repeat them)."""
    allowed = sorted(slot_allowed_placeholders(fact_type, event_type))
    existing_block = "\n".join(f"- {s}" for s in existing) or "(none yet)"
    exclusion_block = f"\nHARD EXCLUSION: {exclusion_note}\n" if exclusion_note else ""
    system = (
        "You write short, plain, business-register template sentences for a B2B "
        "healthcare-software synthetic data generator. You output ONLY valid JSON."
    )
    user = f"""Vertical: {vertical_name}
What this vendor sells: {vendor_what}
{exclusion_block}
Write exactly {needed} NEW template sentences for fact_type="{fact_type}" in an
event_type="{event_type}" context. They must be DISTINCT from each other and
from the sentences already written below (different structure and angle, not
synonym swaps). Use ONLY these placeholder tokens, written literally:
{allowed}
Plain declarative business register, under 30 words each, no markdown.

Already written (do not repeat these):
{existing_block}

Respond with ONLY: {{"sentences": ["...", "..."]}}
"""
    return system, user


def build_decoy_regen_prompt(
    vertical_name: str,
    vendor_what: str,
    decoy_spec: dict,
    exclusion_note: str,
    rejected_examples: list[str],
) -> tuple[str, str]:
    """Regenerates ONE decoy class in isolation -- used when every
    candidate the big call produced for this class failed curation (a
    stray placeholder, excluded vocabulary, empty string). Tells the
    model what was wrong with the earlier attempts rather than silently
    re-asking the same question."""
    exclusion_block = (
        f"\nHARD EXCLUSION -- read carefully: {exclusion_note}\n" if exclusion_note else ""
    )
    rejected_block = (
        "\n".join(f"- {s!r}" for s in rejected_examples) if rejected_examples else "(none)"
    )
    system = (
        "You write short, plain, business-register example sentences for a B2B "
        "healthcare-software synthetic data generator. You output ONLY valid JSON."
    )
    user = f"""Vertical: {vertical_name}
What this vendor sells: {vendor_what}
{exclusion_block}
Write ONE realistic example sentence (in this vertical's voice) of this
near-miss pattern -- a statement that LOOKS like a fact but is NOT one:

id="{decoy_spec["id"]}" near_type="{decoy_spec["near_type"]}" description="{decoy_spec["description"]}"

Write it as a FULLY REALIZED, informal, first-person-sounding sentence a
real person might actually say.

**Critical: invent a specific, concrete, made-up name for anything you'd
otherwise leave blank -- a competitor, a product, a person -- write that
made-up name directly into the sentence as plain text. NEVER write a
curly-brace placeholder like `{{competitor}}` or `{{product}}`.** Example
of the right shape (note the invented name "Meridian", written as plain
text, never in braces): "We looked at Meridian's platform last spring but
stuck with what we have since the integration was already dialed in."

These earlier attempts were rejected (fix whatever was wrong -- a stray
placeholder, excluded vocabulary, or an empty string):
{rejected_block}

Respond with ONLY: {{"example": "..."}}
"""
    return system, user


def generate_for_pack(
    client,
    model: str,
    pack_id: str,
    vertical_name: str,
    vendor_what: str,
    product_kinds: list[str],
    role_titles: list[str],
    decoy_specs: list[dict],
    exclusion_note: str = "",
    temperature: float = 0.9,
    max_tokens: int = 9000,
):
    """One primary call for `pack_id`. Returns `(data, result)` --
    `data` the parsed JSON dict, `result` the raw `LLMResult` (token
    counts) -- and raises if no valid JSON came back after retries. Makes
    NO caching or spend decisions itself; the driver
    (`scripts/data/v2_gen_pack_templates.py`) owns the spend-meter gate
    and the durable raw-response log, since only it knows the run's
    running total."""
    system, user = build_prompt(
        vertical_name, vendor_what, product_kinds, role_titles, decoy_specs, exclusion_note
    )
    last_exc: Exception | None = None
    data = None
    result = None
    for attempt in range(2):
        result = client.complete(
            system=system,
            user=user,
            model=model,
            surface="chat",
            max_tokens=max_tokens,
            temperature=temperature if attempt == 0 else max(0.4, temperature - 0.3),
        )
        if not result.text:
            last_exc = RuntimeError(f"[{pack_id}] empty response from {model}")
            continue
        try:
            data = extract_json(result.text)
            break
        except ValueError as exc:
            last_exc = exc
            print(f"[{pack_id}] attempt {attempt + 1} JSON parse failed: {exc}; retrying")
    if data is None:
        raise RuntimeError(f"[{pack_id}] failed to get valid JSON after retries") from last_exc
    return data, result


# --------------------------------------------------------------------------
# Curation: filter/dedupe/validate what the model returned. No rewriting
# of phrasing -- a template that fails a check is dropped, never edited.
# --------------------------------------------------------------------------

# Exactly the terms the maintainer's hard constraint (2026-09-22) names -- same
# pattern `tests/test_world_generator_v2_packs.py::
# test_senior_living_pack_excludes_monitoring_category` scans with. An
# earlier, broader draft here also caught "track"/"wearable"/"gps"/
# "geofence", which rejected clearly benign sentences ("workflow
# tracking", "compliance tracking" -- ordinary SaaS vocabulary with no
# connection to resident fall/monitoring) so aggressively that decoy/
# claim-template generation for this pack couldn't converge. The
# exclusion prompt (`SENIOR_LIVING_EXCLUSION` in `scripts/data/
# v2_gen_pack_templates.py`) still tells the model to avoid tracking/
# monitoring framing as GUIDANCE; this filter only hard-rejects the five
# terms the guard actually names.
FORBIDDEN_SENIOR_LIVING_PATTERN = re.compile(
    r"\b(fall|monitor\w*|camera|video|sensor)\b",
    re.IGNORECASE,
)


def _normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text.strip().lower())


def curate_claim_templates(
    raw: dict, pack_id: str, is_senior_living: bool
) -> dict[str, dict[str, list[str]]]:
    """Returns `{fact_type: {event_type: [template, ...]}}`, filtered and
    deduplicated. Raises if any fact_type ends up short of 15 unique
    templates after filtering (caller should top up before this, or catch
    and report)."""
    out: dict[str, dict[str, list[str]]] = {}
    seen_per_fact_type: dict[str, set[str]] = {ft: set() for ft in ALL_FACT_TYPES}
    dropped: list[str] = []

    claim_templates = raw.get("claim_templates", {})
    for fact_type, slots in FACT_TYPE_EVENT_SLOTS.items():
        out[fact_type] = {}
        for event_type, _count in slots:
            candidates = claim_templates.get(fact_type, {}).get(event_type, [])
            allowed = slot_allowed_placeholders(fact_type, event_type)
            kept: list[str] = []
            for sentence in candidates:
                sentence = sentence.strip()
                if not sentence:
                    continue
                norm = _normalize(sentence)
                if norm in seen_per_fact_type[fact_type]:
                    dropped.append(f"{fact_type}/{event_type}: dup: {sentence!r}")
                    continue
                tokens = set(_PLACEHOLDER_RE.findall(sentence))
                if not tokens.issubset(_KNOWN_PLACEHOLDERS):
                    dropped.append(f"{fact_type}/{event_type}: unknown token: {sentence!r}")
                    continue
                if not tokens.issubset(allowed):
                    dropped.append(
                        f"{fact_type}/{event_type}: disallowed placeholder: {sentence!r}"
                    )
                    continue
                if len(sentence.split()) > 40:
                    dropped.append(f"{fact_type}/{event_type}: too long: {sentence!r}")
                    continue
                if is_senior_living and FORBIDDEN_SENIOR_LIVING_PATTERN.search(sentence):
                    dropped.append(f"{fact_type}/{event_type}: excluded vocabulary: {sentence!r}")
                    continue
                seen_per_fact_type[fact_type].add(norm)
                kept.append(sentence)
            out[fact_type][event_type] = kept

    short = {
        ft: sum(len(v) for v in slots.values())
        for ft, slots in out.items()
        if sum(len(v) for v in slots.values()) < 15
    }
    if dropped:
        print(f"[{pack_id}] dropped {len(dropped)} candidate template(s):")
        for d in dropped[:20]:
            print("   ", d)
    if short:
        print(f"[{pack_id}] WARNING short after curation: {short}")
    return out


def decoy_is_valid(sentence: str, is_senior_living: bool) -> tuple[bool, str]:
    """One check, shared by the initial curation pass and every
    regeneration attempt, so both apply the exact same rule. Returns
    `(ok, reason)` -- `reason` is only meaningful when `ok` is False."""
    if not sentence.strip():
        return False, "empty"
    if _PLACEHOLDER_RE.search(sentence):
        return False, "contains a curly-brace placeholder"
    if is_senior_living and FORBIDDEN_SENIOR_LIVING_PATTERN.search(sentence):
        return False, "excluded vocabulary"
    return True, ""


def curate_decoys(
    raw: dict, decoy_specs: list[dict], pack_id: str, is_senior_living: bool
) -> tuple[dict[str, str], dict[str, list[str]]]:
    """Returns `(kept, rejected)`: `kept` is `{decoy_id: example}` for
    every decoy class whose candidate passed `decoy_is_valid` UNCHANGED
    (never edited); `rejected` is `{decoy_id: [rejected sentence, ...]}`
    for every class with NO valid candidate -- the caller regenerates
    each of those via `build_decoy_regen_prompt`, it never patches the
    model's text by hand."""
    kept: dict[str, str] = {}
    rejected: dict[str, list[str]] = {}
    raw_examples = raw.get("decoy_examples", {})
    for spec in decoy_specs:
        decoy_id = spec["id"]
        sentence = raw_examples.get(decoy_id, "")
        sentence = sentence.strip() if isinstance(sentence, str) else ""
        ok, reason = decoy_is_valid(sentence, is_senior_living)
        if ok:
            kept[decoy_id] = sentence
        else:
            print(f"[{pack_id}] decoy {decoy_id} rejected ({reason}): {sentence!r}")
            rejected[decoy_id] = [sentence] if sentence else []
    return kept, rejected
