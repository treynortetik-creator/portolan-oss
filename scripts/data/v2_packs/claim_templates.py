# Every one of {account}/{vendor}/{product}/{person}/{date}/{amount}/{days}
# is ALWAYS safely resolvable by the simulator regardless of fact type or
# event type (`simulator._render_claim`'s ctx always has a real value or a
# harmless generic fallback for each -- `person` is drawn for every event,
# not just champion_departure; `amount`/`days` are always freshly rolled).
# `{competitor}` is the one genuine exception: `competitor` stays `None`
# for every event EXCEPT `competitive_eval` (`simulator.emit_event_and_
# facts`), so a template using it outside that one event type would
# render a generic "a competing vendor" instead of a real, anchored
# entity -- restricted to that slot only.
FACT_TYPE_PLACEHOLDERS: dict[str, list[str]] = {
    ft: ["{account}", "{vendor}", "{product}", "{person}", "{date}", "{amount}", "{days}"]
    for ft in [
        "usage",
        "complaint",
        "risk",
        "praise",
        "question",
        "decision",
        "pricing",
        "request",
        "competitor_mention",
        "contact_change",
        "commitment",
        "other",
    ]
}
for _ft in ("competitor_mention", "risk"):
    FACT_TYPE_PLACEHOLDERS[_ft] = [*FACT_TYPE_PLACEHOLDERS[_ft], "{competitor}"]
del _ft


def slot_allowed_placeholders(fact_type: str, event_type: str) -> set[str]:
    allowed = set(FACT_TYPE_PLACEHOLDERS[fact_type])
    if event_type != "competitive_eval":
        allowed.discard("{competitor}")
    return allowed


ALL_FACT_TYPES = list(FACT_TYPE_EVENT_SLOTS.keys())

