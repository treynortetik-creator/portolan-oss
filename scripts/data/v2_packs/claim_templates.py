"""Prompt-building, model-call and STRICT curation for WP2's claim
templates + decoy examples (coordinator review of 7f779a3, 2026-09-22):
these become `Fact.claim` training labels and verbatim decoy spans a
document might quote, so the phrasing must come from an open-weight
OpenRouter model, never Claude. `scripts/data/v2_gen_pack_templates.py`
is the driver that calls this module's functions under a spend-meter
gate and persists every raw response under `var/data/v2_packs/raw/`.

**Curation is drop-only.** Every `curate_*` function here either keeps a
model sentence completely unmodified (past a plain `.strip()`) or drops
it -- never edits, rewrites, or strips content out of a kept sentence.
Coordinator review of 7f779a3: an earlier version of `curate_decoys`
stripped stray placeholder tokens out of a decoy's middle, which changes
the model's own phrasing into something it never actually wrote. A decoy
class (or claim-template slot) that comes back empty after curation is
regenerated by calling the model again for JUST that item -- never
patched by hand.
"""

