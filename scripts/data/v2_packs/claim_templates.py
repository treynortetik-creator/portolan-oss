import re

# (event_type, target_count) per fact_type -- sums to 18-21 per fact type
# (buffer above the schema's 15-per-type floor, since curation rejects a
# few: placeholder violations, forbidden vocabulary, near-duplicates).
# Mirrors the exact event_type/fact_type wiring already in every pack.
